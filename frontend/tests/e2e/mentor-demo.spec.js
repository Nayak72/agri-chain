import { test, expect } from '@playwright/test'
// Requires a running UI/API and seed_demo.py on an isolated demo database.
// Every business mutation is performed through the React interface.
test('six roles: farm through partial delivery and audit', async ({ page }) => {
  const stamp = Date.now()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('response', response => { if (response.status() >= 400 && response.url().includes('/api/')) console.log('API ERROR', response.status(), response.url()) })
  async function login(name, password) {
    if (await page.getByRole('button', { name: 'Sign out', exact: true }).count()) await page.getByRole('button', { name: 'Sign out', exact: true }).click()
    else await page.goto('/login')
    await page.locator('input[type=email]').fill(`${name}@agrichain.com`)
    await page.locator('input[type=password]').fill(password)
    await page.locator('form button[type=submit]').click()
    await expect(page).toHaveURL(/dashboard/)
  }
  const nav = async name => page.getByRole('link', { name, exact: true }).first().click()
  const field = (name) => page.locator(`[name="${name}"]`)
  async function save(button, path) {
    await page.getByRole('button', { name: button, exact: true }).click()
    await expect(page).toHaveURL(path)
  }
  await login('admin', 'Admin123!')
  await nav('Users')
  await expect(page.getByText('farmer1@agrichain.com', { exact: true })).toBeVisible()
  await nav('Produce')
  await expect(page.getByText('TOMATO', { exact: true }).first()).toBeVisible()
  await nav('Farms')
  await page.getByRole('button', { name: 'Register Farm', exact: true }).click()
  await page.getByRole('combobox', { name: 'Farmer', exact: true }).selectOption({ label: 'Nashik Farmer (farmer1@agrichain.com)' })
  for (const [key, value] of Object.entries({ name: `Admin farm ${stamp}`, city: 'Nashik', state: 'Maharashtra', pincode: '422001' })) await field(key).fill(value)
  await save('Save farm', /farms\/[a-f0-9]+$/)

  await login('farmer1', 'Farmer123!')
  await nav('Farms')
  await page.getByRole('button', { name: 'Register Farm', exact: true }).click()
  for (const [key, value] of Object.entries({ name: `Mentor farm ${stamp}`, city: 'Nashik', state: 'Maharashtra', pincode: '422001' })) await field(key).fill(value)
  await save('Save farm', /farms\/[a-f0-9]+$/)
  await nav('Batches')
  await page.getByRole('button', { name: 'Register Harvest Batch', exact: true }).first().click()
  await field('farm_id').selectOption({ label: `Mentor farm ${stamp} (Nashik, Maharashtra)` })
  await field('produce_type').selectOption('TOMATO')
  await field('initial_quantity_kg').fill('2000')
  await save('Generate Batch Record', /batches\/(?!new)[^/]+$/)
  const batchName = await page.locator('h1').innerText()

  await login('warehouse1', 'Warehouse123!')
  await nav('Inventory')
  await page.getByRole('button', { name: 'Warehouse Receipts', exact: true }).click()
  await field('warehouse_id').selectOption({ label: 'Nashik Demo Cold Warehouse' })
  await field('batch_id').selectOption({ label: batchName })
  for (const [key, value] of Object.entries({ received_weight_kg: '2000', accepted_weight_kg: '1950', damaged_weight_kg: '30', rejected_weight_kg: '20', storage_location: 'COLD-A1' })) await field(key).fill(value)
  await page.getByLabel('Store accepted goods in cold storage').check()
  await page.getByRole('button', { name: 'Save receipt', exact: true }).click()
  await expect(page.getByRole('table')).toContainText('1,950')

  await login('buyer1', 'Buyer123!')
  await nav('Purchase Orders')
  await page.getByRole('button', { name: 'New Purchase Order', exact: true }).first().click()
  await page.getByRole('combobox').selectOption({ label: `${batchName} — TOMATO (Mentor farm ${stamp}, Nashik, Maharashtra)` })
  await field('requested_quantity_kg').fill('500')
  await field('unit_price_inr').fill('30')
  await field('preferred_delivery_date').fill(new Date(Date.now() + 86400000 * 3).toISOString().slice(0, 10))
  await save('Generate Purchase Order', /purchase-orders\/[a-f0-9]+$/)
  const orderName = await page.locator('h1').innerText()
  await expect(page.getByText('Placed', { exact: true })).toBeVisible()

  await login('farmer1', 'Farmer123!')
  await nav('Purchase Orders')
  await page.getByText(orderName, { exact: true }).click()
  await page.getByRole('button', { name: 'Accept Contract', exact: true }).click()
  await page.getByRole('button', { name: 'Book Freight Transport', exact: true }).click()
  await field('package_count').fill('100')
  await page.locator('form button[type=submit]').click()
  await expect(page).toHaveURL(/freight-bookings\/[a-f0-9]+$/)
  const bookingName = await page.locator('h1').innerText()

  await login('transporter1', 'Transporter123!')
  await nav('Freight Bookings')
  await page.getByText(bookingName, { exact: true }).click()
  await page.getByRole('button', { name: 'Submit Quotation for this Booking', exact: true }).click()
  await field('planned_distance_km').fill('1050')
  await field('estimated_transit_hours').fill('24')
  await page.getByRole('button', { name: 'Transmit Quotation Bid', exact: true }).click()
  await expect(page.getByText('Quotation submitted successfully to the freight exchange!')).toBeVisible()

  await login('buyer1', 'Buyer123!')
  await nav('Freight Bookings')
  await page.getByText(bookingName, { exact: true }).click()
  await page.getByRole('button', { name: 'Accept Quotation', exact: true }).click()
  await expect(page.getByText('Confirmed', { exact: true })).toBeVisible()

  await login('transporter1', 'Transporter123!')
  await nav('Freight Bookings')
  await page.getByText(bookingName, { exact: true }).click()
  await page.getByRole('button', { name: 'Create Shipment', exact: true }).click()
  await field('vehicle_id').selectOption({ index: 1 })
  const driverOption = page.locator('select[name=driver_id] option').filter({ hasText: 'Reefer Driver 1' })
  await field('driver_id').selectOption(await driverOption.getAttribute('value'))
  await save('Confirm Shipment Dispatch', /shipments\/[a-f0-9]+$/)
  const shipmentName = await page.locator('h1').innerText()
  await page.getByRole('button', { name: 'Log Cargo Loading', exact: true }).first().click()
  await page.getByRole('dialog').locator('input[type=number]').first().fill('500')
  await page.getByRole('button', { name: 'Confirm Loaded', exact: true }).click()
  await page.getByRole('button', { name: 'Dispatch Consignment', exact: true }).click()
  await page.getByRole('button', { name: 'Start Transit', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Mark Arrived at Destination', exact: true })).toBeVisible()

  await login('driver1', 'Driver123!')
  await nav('Shipments')
  await page.getByText(shipmentName, { exact: true }).click()
  await page.getByRole('button', { name: 'Log Checkpoint', exact: true }).click()
  await page.getByRole('dialog').locator('input').nth(0).fill('Pune tollway')
  await page.getByRole('dialog').locator('input').nth(1).fill('Pune')
  await page.getByRole('button', { name: 'Save Checkpoint', exact: true }).click()
  await expect(page.getByText('Pune tollway', { exact: true })).toBeVisible()
  await nav('Cold-Chain')
  await page.locator('select').nth(0).selectOption({ label: `${shipmentName} — IN_TRANSIT` })
  await page.locator('select').nth(1).selectOption('TEMP_EXCURSION')
  await page.getByLabel('Playback speed').selectOption('60')
  await page.getByRole('button', { name: 'Start simulation', exact: true }).click()
  for (let i = 0; i < 4; i++) {
    const response = page.waitForResponse(r => r.url().includes('next-reading') && r.request().method() === 'POST')
    await page.getByRole('button', { name: 'Simulate reading', exact: true }).click()
    expect((await response).ok()).toBeTruthy()
  }
  await expect(page.getByText('CRITICAL', { exact: true }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Acknowledge', exact: true }).first().click()
  await page.getByRole('button', { name: 'Resolve', exact: true }).first().click()
  await page.getByRole('dialog').locator('textarea').fill('Simulated reefer inspection; verified setpoint 10°C')
  await page.getByRole('button', { name: 'Confirm Action', exact: true }).click()
  await page.getByRole('button', { name: 'Start auto-play', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Stop auto-play', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  await page.getByRole('button', { name: 'Stop', exact: true }).click()

  await login('transporter1', 'Transporter123!')
  await nav('Shipments')
  await page.getByText(shipmentName, { exact: true }).click()
  await page.getByRole('button', { name: 'Mark Arrived at Destination', exact: true }).click()
  await page.getByRole('button', { name: 'Set Out for Delivery', exact: true }).click()
  await login('buyer1', 'Buyer123!')
  await nav('Deliveries')
  await page.getByRole('combobox').selectOption({ label: shipmentName })
  await page.getByLabel('Delivered kg', { exact: true }).fill('480')
  await page.getByLabel('Damaged kg', { exact: true }).fill('15')
  await page.getByLabel('Missing kg', { exact: true }).fill('5')
  await page.getByRole('button', { name: 'Confirm delivery', exact: true }).click()
  await expect(page.getByRole('link', { name: /^DR-/ }).first()).toBeVisible()
  await nav('Shipments')
  await page.getByText(shipmentName, { exact: true }).click()
  await expect(page.getByText('Partially Delivered', { exact: true })).toBeVisible()
  await login('admin', 'Admin123!')
  await nav('Analytics')
  await nav('Ledger')
  await page.getByRole('button', { name: 'Verify Ledger Integrity', exact: true }).click()
  await expect(page.getByText(/Chain.*Valid|Integrity.*Verified|Verification.*Passed/i).first()).toBeVisible()
  expect(errors).toEqual([])
})
